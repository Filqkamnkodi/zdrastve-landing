const relatedFor = (slug: string) =>
  servicesList
    .filter((s) => s.slug !== slug)
    .slice(0, 3)
    .map((s) => s.slug);

function baseEntry(slug: string): ServiceData {
  const meta = servicesList.find((s) => s.slug === slug)!;
  return {
    slug,
    title: meta.title,
    eyebrow: "Медицински услуги",
    intro: meta.desc,
    heroImage: imageFor(slug),
    overviewTitle: "За услугата",
    overview: defaultOverview,
    includes: [],
    recommendedFor: [],
    faqTitle: "Често задавани въпроси",
    faq: [],
    ...defaultCta,
    relatedServices: relatedFor(slug),
  };
}

